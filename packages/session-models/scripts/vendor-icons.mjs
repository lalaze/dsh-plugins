// Regenerate src/client/icons.ts from an extracted @lobehub/icons-static-svg package (MIT).
// Usage: node scripts/vendor-icons.mjs <path-to-extracted-package>
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const SOURCES = {
  claude: 'claude', openai: 'openai', deepseek: 'deepseek', gemini: 'gemini', grok: 'grok', qwen: 'qwen', kimi: 'kimi',
  zhipu: 'zhipu', doubao: 'doubao', minimax: 'minimax', mistral: 'mistral', antigravity: 'antigravity', codebuddy: 'codebuddy',
};
const source = process.argv[2];
if (!source) throw new Error('Pass the extracted @lobehub/icons-static-svg package directory.');
const { name, version, license } = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'));
if (name !== '@lobehub/icons-static-svg' || license !== 'MIT') throw new Error(`Unexpected icon package: ${name} (${license})`);

// Masks only read alpha, so keep geometry and drop presentation and size attributes.
const clean = svg => svg
  .replace(/<title>[\s\S]*?<\/title>/g, '')
  .replace(/\s(?:height|width|style)="[^"]*"/g, '')
  .replace(/fill="currentColor"/g, 'fill="#000"')
  .replace(/\s+/g, ' ')
  .trim();

const entries = [];
for (const [id, file] of Object.entries(SOURCES)) {
  const svg = clean(await readFile(join(source, 'icons', `${file}.svg`), 'utf8'));
  if (!svg.startsWith('<svg') || /<script|on\w+=/i.test(svg)) throw new Error(`Unexpected markup in ${file}.svg`);
  entries.push(`  ${id}: ${JSON.stringify(svg)},`);
}
const output = `// Generated by scripts/vendor-icons.mjs from ${name}@${version} (MIT, © LobeHub). Do not edit by hand.
// See THIRD_PARTY_NOTICES.md. The generic glyph is original to this package.
export const ICONS = {
${entries.join('\n')}
  generic: '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="#000" d="M12 2l2.4 7.6L22 12l-7.6 2.4L12 22l-2.4-7.6L2 12l7.6-2.4z"/></svg>',
} as const;
`;
await writeFile(resolve(import.meta.dirname, '../src/client/icons.ts'), output);
console.log(`Wrote ${entries.length + 1} icons from ${name}@${version}`);
