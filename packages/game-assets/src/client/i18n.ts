export const { ui, installLocale, localizeError } = i18n;

/** Errors of image APIs carry a name, a status or the API's own words; the frame around them is translated. */
const PICTURE_ERRORS: [RegExp, string, string[]][] = [
  [/^(.+) refused the request \((\d+)\): ([\s\S]*)$/, '{name} refused the request ({status}): {detail}', ['name', 'status', 'detail']],
  [/^(.+) answered without a picture: ([\s\S]*)$/, '{name} answered without a picture: {detail}', ['name', 'detail']],
  [/^(.+) answered without a picture$/, '{name} answered without a picture', ['name']],
  [/^(.+) did not answer with JSON: ([\s\S]*)$/, '{name} did not answer with JSON: {detail}', ['name', 'detail']],
  [/^(\S+) could not be reached: ([\s\S]*)$/, '{host} could not be reached: {detail}', ['host', 'detail']],
  [/^(.+) is not the image its name says$/, '{path} is not the image its name says', ['path']],
  [/^The picture could not be downloaded \((\d+)\)$/, 'The picture could not be downloaded ({status})', ['status']],
];
export function localizePictureError(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  for (const [pattern, key, names] of PICTURE_ERRORS) {
    const match = pattern.exec(message);
    if (match) return ui(key, Object.fromEntries(names.map((name, i) => [name, match[i + 1]])));
  }
  return localizeError(error);
}
