// Copies the Lucide icons the phone app uses into app/src/lucide.ts, so the app needs no icon dependency.
// Usage: node scripts/vendor-lucide.mjs <path to an installed lucide-react package>
import { readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const NAMES = [
  'archive', 'archive-restore', 'arrow-down', 'arrow-up', 'bot', 'brain', 'check', 'chevron-down', 'chevron-left', 'chevron-right',
  'circle-check', 'circle-play', 'copy', 'ellipsis', 'file-pen-line', 'file-plus', 'file-text', 'folder', 'globe', 'list', 'list-filter',
  'list-todo', 'monitor', 'moon', 'paperclip', 'pencil', 'plus', 'refresh-cw', 'search', 'settings', 'shield', 'sparkle', 'sparkles',
  'square', 'square-terminal', 'text-search', 'triangle-alert', 'wifi-off', 'wrench', 'x',
]

const source = process.argv[2]
if (!source) { console.error('Usage: node scripts/vendor-lucide.mjs <lucide-react directory>'); process.exit(1) }
const { version } = JSON.parse(await readFile(join(source, 'package.json'), 'utf8'))
const icons = {}
for (const name of NAMES) {
  const module = await import(join(resolve(source), 'dist/esm/icons', `${name}.js`))
  icons[name] = module.__iconNode.map(([tag, { key: _key, ...attributes }]) => [tag, attributes])
}
const body = Object.entries(icons).map(([name, nodes]) => `  ${JSON.stringify(name)}: ${JSON.stringify(nodes)},`).join('\n')
await writeFile(new URL('../app/src/lucide.ts', import.meta.url), `// Generated by scripts/vendor-lucide.mjs from lucide-react ${version} (ISC, © Lucide Icons and Contributors; see
// THIRD_PARTY_NOTICES.md). Do not edit by hand.
export type IconNode = readonly (readonly [string, Readonly<Record<string, string>>])[]

export const LUCIDE = {
${body}
} as const satisfies Record<string, IconNode>
`)
console.log(`Wrote ${NAMES.length} icons from lucide-react ${version}`)
