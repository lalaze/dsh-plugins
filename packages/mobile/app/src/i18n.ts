const language = languageOf(globalThis.navigator?.language)
export const locale = language === 'zh' ? 'zh-CN' : 'en-US'
export const ui = (text: string, params?: Params): string => fill(language === 'zh' && Object.hasOwn(zh, text) ? zh[text] : text, params)
export const errorText = (error: unknown) => ui(error instanceof Error ? error.message : String(error))

export function ago(time: number | undefined): string {
  if (!time) return ''
  const seconds = Math.round((Date.now() - time) / 1000)
  if (seconds < 45) return ui('Just now')
  const format = new Intl.RelativeTimeFormat(locale, { numeric: 'auto', style: 'narrow' })
  if (seconds < 3600) return format.format(-Math.round(seconds / 60), 'minute')
  if (seconds < 86_400) return format.format(-Math.round(seconds / 3600), 'hour')
  if (seconds < 7 * 86_400) return format.format(-Math.round(seconds / 86_400), 'day')
  return new Date(time).toLocaleDateString(locale, { month: 'short', day: 'numeric' })
}
